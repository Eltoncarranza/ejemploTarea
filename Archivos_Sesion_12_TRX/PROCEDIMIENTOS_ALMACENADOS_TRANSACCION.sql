CREATE OR ALTER PROCEDURE PA_MOVIMIENTOS_CUENTA
@NUM_CTA CHAR(12)=''
AS
	IF @NUM_CTA = ''
		SELECT * FROM Movimientos
	ELSE
		SELECT * FROM Movimientos
			WHERE num_cta = @NUM_CTA
GO

EXEC PA_MOVIMIENTOS_CUENTA
